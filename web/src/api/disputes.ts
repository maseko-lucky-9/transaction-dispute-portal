import { infiniteQueryOptions, queryOptions } from "@tanstack/react-query";

import type { DisputeFilters } from "@/lib/dispute-filters";

import { apiFetch, apiRequest } from "./client";
import type { operations, components } from "./schema";

/**
 * Generated from `docs/openapi.json` by `npm run gen:types`; never edit by hand. Money is a
 * decimal STRING and times are UTC ISO-8601, exactly as sent.
 */
type Schemas = components["schemas"];
export type DisputeStatus = Schemas["DisputeStatus"];
export type DisputeReason = Schemas["DisputeReason"];
export type DisputeItem = Schemas["DisputeListItem"];
export type TimelineEntry = Schemas["TimelineEntry"];
export type DisputeTransaction = Schemas["TransactionSummary"];
export type DisputeDetail = Schemas["DisputeDetail"];
export type DisputePage = Schemas["DisputeListResponse"];
/**
 * `id` is generated by the client, ONCE per opened form: a retry must send the same id.
 * `amount` is a decimal string with at most 2 decimals; omitted disputes the full amount.
 */
export type CreateDisputeRequest = Schemas["CreateDisputeRequest"];
export type ListDisputesQuery = NonNullable<operations["ListDisputes"]["parameters"]["query"]>;

/** A dispute with the ETag it was read with: withdraw must echo it back in If-Match. */
export interface DisputeWithEtag {
  dispute: DisputeDetail;
  etag: string | null;
}

export const disputeKeys = {
  all: ["disputes"] as const,
  list: (filters: DisputeFilters) => ["disputes", "list", filters] as const,
  detail: (id: string) => ["disputes", "detail", id] as const,
};
export const disputeReasonsKey = ["dispute-reasons"] as const;

const withEtag = (response: { data: DisputeDetail; headers: Headers }): DisputeWithEtag => ({
  dispute: response.data,
  etag: response.headers.get("ETag"),
});

/** `GET /api/v1/dispute-reasons`: the catalogue the form's select is built from. */
export function fetchDisputeReasons(signal?: AbortSignal): Promise<DisputeReason[]> {
  return apiFetch<DisputeReason[]>("/api/v1/dispute-reasons", signal ? { signal } : {});
}

/** Reasons barely change: keep them for the session rather than refetching per form. */
export const disputeReasonsOptions = queryOptions({
  queryKey: disputeReasonsKey,
  queryFn: ({ signal }) => fetchDisputeReasons(signal),
  staleTime: 10 * 60_000,
});

/**
 * `POST /api/v1/disputes`: 201 for a new dispute, 200 when the SAME id is replayed (a retry
 * after a lost response). Both are success and carry the dispute and its ETag.
 */
export async function createDispute(
  body: CreateDisputeRequest,
): Promise<DisputeWithEtag & { replayed: boolean }> {
  const response = await apiRequest<DisputeDetail>("/api/v1/disputes", {
    method: "POST",
    json: body,
  });
  return { ...withEtag(response), replayed: response.status === 200 };
}

/** `GET /api/v1/disputes`: the history, newest first, all statuses. */
export function fetchDisputePage(
  filters: DisputeFilters,
  cursor: string | undefined,
  signal?: AbortSignal,
): Promise<DisputePage> {
  // `satisfies` ties every name and value to the generated operation, as for transactions.
  const query = {
    limit: filters.limit,
    status: filters.status,
    cursor,
  } satisfies ListDisputesQuery;
  const params = new URLSearchParams();
  for (const [name, value] of Object.entries(query)) {
    if (value !== undefined && value !== "") params.set(name, String(value));
  }
  return apiFetch<DisputePage>(`/api/v1/disputes?${params.toString()}`, signal ? { signal } : {});
}

export function disputesInfiniteOptions(filters: DisputeFilters) {
  return infiniteQueryOptions({
    queryKey: disputeKeys.list(filters),
    queryFn: ({ pageParam, signal }) => fetchDisputePage(filters, pageParam, signal),
    initialPageParam: undefined as string | undefined,
    getNextPageParam: (lastPage) => lastPage.nextCursor ?? undefined,
    refetchOnWindowFocus: false,
    staleTime: 60_000,
  });
}

/** `GET /api/v1/disputes/{id}`: the dispute and the ETag to withdraw it with. */
export async function fetchDispute(id: string, signal?: AbortSignal): Promise<DisputeWithEtag> {
  return withEtag(
    await apiRequest<DisputeDetail>(
      `/api/v1/disputes/${encodeURIComponent(id)}`,
      signal ? { signal } : {},
    ),
  );
}

export const disputeDetailOptions = (id: string) =>
  queryOptions({
    queryKey: disputeKeys.detail(id),
    queryFn: ({ signal }) => fetchDispute(id, signal),
    // A dispute can change under the customer (an agent acts), and withdraw needs the current
    // ETag: always revalidate when the page is opened.
    staleTime: 0,
  });

/**
 * `POST /api/v1/disputes/{id}/withdraw` with `If-Match`. A missing ETag is sent as no header at
 * all: the server answers 428, which the page treats as a bug rather than guessing a value.
 */
export async function withdrawDispute(id: string, etag: string | null): Promise<DisputeWithEtag> {
  return withEtag(
    await apiRequest<DisputeDetail>(`/api/v1/disputes/${encodeURIComponent(id)}/withdraw`, {
      method: "POST",
      headers: etag ? { "If-Match": etag } : {},
    }),
  );
}
